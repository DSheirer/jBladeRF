package io.github.dsheirer.bladerf.internal;

import static java.lang.foreign.MemoryLayout.PathElement.groupElement;
import static java.lang.foreign.MemoryLayout.paddingLayout;
import static java.lang.foreign.MemoryLayout.sequenceLayout;
import static java.lang.foreign.MemoryLayout.structLayout;
import static java.lang.foreign.ValueLayout.ADDRESS;
import static java.lang.foreign.ValueLayout.JAVA_BYTE;
import static java.lang.foreign.ValueLayout.JAVA_DOUBLE;
import static java.lang.foreign.ValueLayout.JAVA_FLOAT;
import static java.lang.foreign.ValueLayout.JAVA_INT;
import static java.lang.foreign.ValueLayout.JAVA_LONG;
import static java.lang.foreign.ValueLayout.JAVA_SHORT;

import java.lang.foreign.GroupLayout;
import java.lang.foreign.MemoryLayout;
import java.lang.foreign.MemorySegment;
import java.nio.charset.StandardCharsets;

/**
 * Memory layouts of the structures in {@code libbladeRF.h}.
 *
 * <p>These are written by hand rather than generated by jextract because every
 * field has a fixed width, so a single set of layouts is correct on all of the
 * supported 64-bit platforms. {@code LibraryTest} checks their sizes and offsets
 * against the values that a C compiler reports.
 */
public final class Layouts {
    /** {@code BLADERF_DESCRIPTION_LENGTH}. */
    public static final int DESCRIPTION_LENGTH = 33;
    /** {@code BLADERF_SERIAL_LENGTH}. */
    public static final int SERIAL_LENGTH = 33;
    /** Size of the first page of the OTP, the only part libbladeRF can access. */
    public static final int OTP_LENGTH = 256;

    /** {@code struct bladerf_devinfo}. */
    public static final GroupLayout DEVINFO = structLayout(
        JAVA_INT.withName("backend"),
        sequenceLayout(SERIAL_LENGTH, JAVA_BYTE).withName("serial"),
        JAVA_BYTE.withName("usb_bus"),
        JAVA_BYTE.withName("usb_addr"),
        paddingLayout(1),
        JAVA_INT.withName("instance"),
        sequenceLayout(DESCRIPTION_LENGTH, JAVA_BYTE).withName("manufacturer"),
        sequenceLayout(DESCRIPTION_LENGTH, JAVA_BYTE).withName("product"),
        paddingLayout(2));

    /** {@code struct bladerf_backendinfo}. */
    public static final GroupLayout BACKENDINFO = structLayout(
        JAVA_INT.withName("handle_count"),
        paddingLayout(4),
        ADDRESS.withName("handle"),
        JAVA_INT.withName("lock_count"),
        paddingLayout(4),
        ADDRESS.withName("lock"));

    /** {@code struct bladerf_range}. */
    public static final GroupLayout RANGE = structLayout(
        JAVA_LONG.withName("min"),
        JAVA_LONG.withName("max"),
        JAVA_LONG.withName("step"),
        JAVA_FLOAT.withName("scale"),
        paddingLayout(4));

    /** {@code struct bladerf_serial}. */
    public static final GroupLayout SERIAL = structLayout(
        sequenceLayout(SERIAL_LENGTH, JAVA_BYTE).withName("serial"));

    /** {@code struct bladerf_version}. */
    public static final GroupLayout VERSION = structLayout(
        JAVA_SHORT.withName("major"),
        JAVA_SHORT.withName("minor"),
        JAVA_SHORT.withName("patch"),
        paddingLayout(2),
        ADDRESS.withName("describe"));

    /** {@code struct bladerf_gain_modes}. */
    public static final GroupLayout GAIN_MODES = structLayout(
        ADDRESS.withName("name"),
        JAVA_INT.withName("mode"),
        paddingLayout(4));

    /** {@code struct bladerf_loopback_modes}. */
    public static final GroupLayout LOOPBACK_MODES = structLayout(
        ADDRESS.withName("name"),
        JAVA_INT.withName("mode"),
        paddingLayout(4));

    /** {@code struct bladerf_rational_rate}. */
    public static final GroupLayout RATIONAL_RATE = structLayout(
        JAVA_LONG.withName("integer"),
        JAVA_LONG.withName("num"),
        JAVA_LONG.withName("den"));

    /** {@code struct bladerf_trigger}. */
    public static final GroupLayout TRIGGER = structLayout(
        JAVA_INT.withName("channel"),
        JAVA_INT.withName("role"),
        JAVA_INT.withName("signal"),
        paddingLayout(4),
        JAVA_LONG.withName("options"));

    /** {@code struct bladerf_quick_tune}, which is opaque to Java. */
    public static final GroupLayout QUICK_TUNE = structLayout(
        sequenceLayout(3, JAVA_INT).withName("data"));

    /** {@code struct bladerf_metadata}. */
    public static final GroupLayout METADATA = structLayout(
        JAVA_LONG.withName("timestamp"),
        JAVA_INT.withName("flags"),
        JAVA_INT.withName("status"),
        JAVA_INT.withName("actual_count"),
        sequenceLayout(32, JAVA_BYTE).withName("reserved"),
        paddingLayout(4));

    /** {@code struct bladerf_image}. */
    public static final GroupLayout IMAGE = structLayout(
        sequenceLayout(8, JAVA_BYTE).withName("magic"),
        sequenceLayout(32, JAVA_BYTE).withName("checksum"),
        VERSION.withName("version"),
        JAVA_LONG.withName("timestamp"),
        sequenceLayout(SERIAL_LENGTH + 1, JAVA_BYTE).withName("serial"),
        sequenceLayout(128, JAVA_BYTE).withName("reserved"),
        paddingLayout(2),
        JAVA_INT.withName("type"),
        JAVA_INT.withName("address"),
        JAVA_INT.withName("length"),
        ADDRESS.withName("data"));

    /** {@code struct bladerf_gain_cal_entry}. */
    public static final GroupLayout GAIN_CAL_ENTRY = structLayout(
        JAVA_LONG.withName("freq"),
        JAVA_DOUBLE.withName("gain_corr"));

    /** {@code struct bladerf_gain_cal_tbl}. */
    public static final GroupLayout GAIN_CAL_TBL = structLayout(
        VERSION.withName("version"),
        JAVA_INT.withName("ch"),
        JAVA_BYTE.withName("enabled"),
        paddingLayout(3),
        JAVA_INT.withName("n_entries"),
        paddingLayout(4),
        JAVA_LONG.withName("start_freq"),
        JAVA_LONG.withName("stop_freq"),
        ADDRESS.withName("entries"),
        JAVA_INT.withName("gain_target"),
        paddingLayout(4),
        JAVA_LONG.withName("file_path_len"),
        ADDRESS.withName("file_path"),
        JAVA_INT.withName("state"),
        paddingLayout(4));

    /** {@code struct bladerf_lms_dc_cals}. */
    public static final GroupLayout LMS_DC_CALS = structLayout(
        JAVA_SHORT.withName("lpf_tuning"),
        JAVA_SHORT.withName("tx_lpf_i"),
        JAVA_SHORT.withName("tx_lpf_q"),
        JAVA_SHORT.withName("rx_lpf_i"),
        JAVA_SHORT.withName("rx_lpf_q"),
        JAVA_SHORT.withName("dc_ref"),
        JAVA_SHORT.withName("rxvga2a_i"),
        JAVA_SHORT.withName("rxvga2a_q"),
        JAVA_SHORT.withName("rxvga2b_i"),
        JAVA_SHORT.withName("rxvga2b_q"));

    /** {@code bladerf_rf_switch_config}. */
    public static final GroupLayout RF_SWITCH_CONFIG = structLayout(
        JAVA_INT.withName("tx1_rfic_port"),
        JAVA_INT.withName("tx1_spdt_port"),
        JAVA_INT.withName("tx2_rfic_port"),
        JAVA_INT.withName("tx2_spdt_port"),
        JAVA_INT.withName("rx1_rfic_port"),
        JAVA_INT.withName("rx1_spdt_port"),
        JAVA_INT.withName("rx2_rfic_port"),
        JAVA_INT.withName("rx2_spdt_port"));

    private Layouts() {
    }

    /** Returns the byte offset of a named field of a structure. */
    public static long offset(MemoryLayout layout, String field) {
        return layout.byteOffset(groupElement(field));
    }

    /** Reads an unsigned 8-bit field. */
    public static int u8(MemorySegment segment, MemoryLayout layout, String field) {
        return Byte.toUnsignedInt(segment.get(JAVA_BYTE, offset(layout, field)));
    }

    /** Reads an unsigned 16-bit field. */
    public static int u16(MemorySegment segment, MemoryLayout layout, String field) {
        return Short.toUnsignedInt(segment.get(JAVA_SHORT, offset(layout, field)));
    }

    /** Reads a signed 16-bit field. */
    public static short i16(MemorySegment segment, MemoryLayout layout, String field) {
        return segment.get(JAVA_SHORT, offset(layout, field));
    }

    /** Reads a signed 32-bit field, which is how C enums and {@code int} are stored. */
    public static int i32(MemorySegment segment, MemoryLayout layout, String field) {
        return segment.get(JAVA_INT, offset(layout, field));
    }

    /** Reads an unsigned 32-bit field. */
    public static long u32(MemorySegment segment, MemoryLayout layout, String field) {
        return Integer.toUnsignedLong(i32(segment, layout, field));
    }

    /** Reads a 64-bit field. */
    public static long i64(MemorySegment segment, MemoryLayout layout, String field) {
        return segment.get(JAVA_LONG, offset(layout, field));
    }

    /** Reads a 32-bit floating point field. */
    public static float f32(MemorySegment segment, MemoryLayout layout, String field) {
        return segment.get(JAVA_FLOAT, offset(layout, field));
    }

    /** Reads a pointer field. */
    public static MemorySegment pointer(MemorySegment segment, MemoryLayout layout, String field) {
        return segment.get(ADDRESS, offset(layout, field));
    }

    /** Returns the part of a structure that holds a nested field. */
    public static MemorySegment slice(MemorySegment segment, GroupLayout layout, String field) {
        return segment.asSlice(offset(layout, field), layout.select(groupElement(field)).byteSize());
    }

    /** Reads a character array field that may fill its space without a terminator. */
    public static String string(MemorySegment segment, GroupLayout layout, String field) {
        MemorySegment chars = slice(segment, layout, field);
        int length = 0;
        while (length < chars.byteSize() && chars.get(JAVA_BYTE, length) != 0) {
            length++;
        }
        return new String(chars.asSlice(0, length).toArray(JAVA_BYTE), StandardCharsets.UTF_8);
    }

    /** Writes a NUL-terminated string to a character array field. */
    public static void putString(MemorySegment segment, GroupLayout layout, String field, String value) {
        MemorySegment chars = slice(segment, layout, field);
        byte[] bytes = value.getBytes(StandardCharsets.UTF_8);
        if (bytes.length >= chars.byteSize()) {
            throw new IllegalArgumentException(field + " is too long: " + value);
        }
        chars.fill((byte) 0);
        MemorySegment.copy(bytes, 0, chars, JAVA_BYTE, 0, bytes.length);
    }
}
